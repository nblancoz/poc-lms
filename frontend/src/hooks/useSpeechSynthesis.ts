import { useCallback, useEffect, useRef, useState } from 'react';

/**
 * Strips markdown symbols, cleans emojis, and adds natural punctuation pauses
 * so speech synthesis reads like a real human tutor instead of a monotone robot.
 */
export function cleanMarkdownForSpeech(markdown: string): string {
  if (!markdown) return '';

  return (
    markdown
      // Replace code blocks with natural pedagogical phrasing
      .replace(/```[\s\S]*?```/g, ' Aquí hay un bloque de código explicativo. ')
      // Replace inline code `code`
      .replace(/`([^`]+)`/g, '$1')
      // Clean headers and ensure they end in a pause
      .replace(/^#{1,6}\s*(.+)$/gm, '$1. ')
      // Remove markdown links [text](url) -> text
      .replace(/\[([^\]]+)\]\([^)]+\)/g, '$1')
      // Remove images ![alt](url) -> alt
      .replace(/!\[([^\]]*)\]\([^)]+\)/g, '$1')
      // Remove square brackets around text placeholders [texto] -> texto
      .replace(/\[([^\]]+)\]/g, '$1')
      // Remove bold and italics **text**, *text*, __text__, _text_
      .replace(/[*_]{1,3}([^*_]+)[*_]{1,3}/g, '$1')
      // Remove blockquotes >
      .replace(/^>\s*/gm, '')
      // Remove horizontal rules
      .replace(/^[-*_]{3,}\s*$/gm, ' ')
      // Replace table pipes with commas/spaces for cadence
      .replace(/\|/g, ', ')
      // Ensure bullet points and numbered lists end with a period/pause
      .replace(/^[\s]*[-*+]\s+(.+)$/gm, '$1. ')
      .replace(/^[\s]*\d+\.\s+(.+)$/gm, '$1. ')
      // Strip emojis (e.g. 👋, 😊, ✨) so the synthesizer doesn't read their raw descriptions
      .replace(
        /[\u{1F600}-\u{1F64F}\u{1F300}-\u{1F5FF}\u{1F680}-\u{1F6FF}\u{1F1E0}-\u{1F1FF}\u{2600}-\u{26FF}\u{2700}-\u{27BF}]/gu,
        '',
      )
      // Convert common symbols to spoken words
      .replace(/\s*&\s*/g, ' y ')
      .replace(/\s*\/\s*/g, ' o ')
      .replace(/%/g, ' por ciento')
      // Clean up multiple periods or commas
      .replace(/\.{2,}/g, '.')
      .replace(/,\s*,+/g, ',')
      // Clean up horizontal whitespace while preserving line breaks
      .replace(/[ \t]+/g, ' ')
      .replace(/\n\s*\n+/g, '\n')
      .trim()
  );
}

export interface SpeechSegment {
  text: string;
  lang: 'es' | 'en';
}

/**
 * Merges adjacent segments that share the same spoken language to produce
 * a seamless, natural speech flow with optimal pauses.
 */
export function mergeAdjacentSegments(segments: SpeechSegment[]): SpeechSegment[] {
  const merged: SpeechSegment[] = [];
  for (const seg of segments) {
    const text = seg.text.trim();
    if (!text || text === '.') continue;
    const prev = merged[merged.length - 1];
    if (prev && prev.lang === seg.lang) {
      prev.text = `${prev.text}. ${text}`;
    } else {
      merged.push({ text, lang: seg.lang });
    }
  }
  return merged;
}

/**
 * Segments speech text into English and Spanish sections so phrases and dialogues
 * are pronounced with authentic native accents instead of being forced into Spanish phonetics.
 *
 * Uses standard semantic HTML <span lang="en">...</span> tags generated by the AI tutor
 * as primary segmentation, with an intelligent quote-based fallback for untagged text.
 */
export function createSpeechSegments(text: string): SpeechSegment[] {
  if (!text) return [];

  // 1. Semantic standard: <span lang="en">...</span>
  // Generates bilingual segments based on HTML/accessibility tags produced by the AI tutor
  if (/<span\s+lang=["']en["']>[\s\S]*?<\/span>/i.test(text)) {
    const parts = text.split(/(<span\s+lang=["']en["']>[\s\S]*?<\/span>)/gi);
    const rawSegments: SpeechSegment[] = [];

    for (const part of parts) {
      const match = /^<span\s+lang=["']en["']>([\s\S]*?)<\/span>$/i.exec(part.trim());
      if (match && match[1]) {
        // Strip wrapper quotes from the English segment and clean markdown
        const clean = cleanMarkdownForSpeech(match[1])
          .replace(/^["“\s]+|[”"\s]+$/g, '')
          .trim();
        if (clean) {
          rawSegments.push({ text: clean, lang: 'en' });
        }
      } else {
        const clean = cleanMarkdownForSpeech(part).trim();
        if (clean && clean !== '.') {
          rawSegments.push({ text: clean, lang: 'es' });
        }
      }
    }

    return mergeAdjacentSegments(rawSegments);
  }

  // 2. Fallback for untagged text (legacy messages or unformatted replies):
  // Isolates quoted phrases ("...") without Spanish characters (á, é, í, ó, ú, ñ, ¿, ¡) for English voice
  const parts = text.split(/("[\s\S]*?"|“[\s\S]*?”)/g);
  const rawSegments: SpeechSegment[] = [];

  for (const part of parts) {
    const isQuote = /^["“]/.test(part.trim());
    if (isQuote) {
      const clean = cleanMarkdownForSpeech(part)
        .replace(/^["“\s]+|[”"\s]+$/g, '')
        .trim();
      if (!clean || clean === '.') continue;
      const isSpanish = /[áéíóúüñ¿¡]/i.test(clean);
      rawSegments.push({ text: clean, lang: isSpanish ? 'es' : 'en' });
    } else {
      const clean = cleanMarkdownForSpeech(part).trim();
      if (clean && clean !== '.') {
        rawSegments.push({ text: clean, lang: 'es' });
      }
    }
  }

  return mergeAdjacentSegments(rawSegments);
}

/**
 * Selects the most natural, high-fidelity voice available for a given language code.
 * Prioritizes neural, enhanced, and online voices over legacy compact synthesizers.
 */
function pickBestVoice(
  voices: SpeechSynthesisVoice[],
  langCode: 'es' | 'en',
): SpeechSynthesisVoice | null {
  if (voices.length === 0) return null;

  const matchingVoices = voices.filter(
    (v) => v.lang.toLowerCase().startsWith(`${langCode}-`) || v.lang.toLowerCase() === langCode,
  );

  if (matchingVoices.length === 0) return null;

  // 1. High-fidelity Neural / Natural / Google / Enhanced voices
  const highQualityMarkers = [
    'natural',
    'google',
    'enhanced',
    'premium',
    'online',
    'siri',
    'neural',
  ];
  const naturalVoice = matchingVoices.find((v) => {
    const name = v.name.toLowerCase();
    return highQualityMarkers.some((marker) => name.includes(marker));
  });
  if (naturalVoice) return naturalVoice;

  // 2. High-quality standard named voices (avoid compact legacy voices)
  const nonCompactVoice = matchingVoices.find((v) => !v.name.toLowerCase().includes('compact'));
  if (nonCompactVoice) return nonCompactVoice;

  // 3. Default voice or first available
  return matchingVoices.find((v) => v.default) || matchingVoices[0] || null;
}

export interface UseSpeechSynthesisResult {
  isSupported: boolean;
  isSpeaking: boolean;
  speakingMessageId: string | null;
  speak: (messageId: string, text: string) => void;
  stop: () => void;
  toggle: (messageId: string, text: string) => void;
}

export function useSpeechSynthesis(): UseSpeechSynthesisResult {
  const [isSpeaking, setIsSpeaking] = useState(false);
  const [speakingMessageId, setSpeakingMessageId] = useState<string | null>(null);

  const isSupported = typeof window !== 'undefined' && 'speechSynthesis' in window;
  const voicesRef = useRef<SpeechSynthesisVoice[]>([]);

  // Cache available voices and listen for async voiceschanged event
  useEffect(() => {
    if (!isSupported) return;

    const updateVoices = () => {
      try {
        const loaded = window.speechSynthesis.getVoices();
        if (loaded.length > 0) {
          voicesRef.current = loaded;
        }
      } catch {
        // Ignored
      }
    };

    updateVoices();
    window.speechSynthesis.addEventListener('voiceschanged', updateVoices);

    return () => {
      window.speechSynthesis.removeEventListener('voiceschanged', updateVoices);
    };
  }, [isSupported]);

  const stop = useCallback(() => {
    if (typeof window !== 'undefined' && 'speechSynthesis' in window) {
      try {
        window.speechSynthesis.cancel();
      } catch {
        // Ignored
      }
    }
    setIsSpeaking(false);
    setSpeakingMessageId(null);
  }, []);

  const speak = useCallback(
    (messageId: string, markdownText: string) => {
      if (!isSupported) return;

      // Stop any existing speech
      stop();

      const segments = createSpeechSegments(markdownText);
      if (segments.length === 0) return;

      const voices =
        voicesRef.current.length > 0 ? voicesRef.current : window.speechSynthesis.getVoices();
      const spanishVoice = pickBestVoice(voices, 'es');
      const englishVoice = pickBestVoice(voices, 'en');

      const utterances: SpeechSynthesisUtterance[] = segments.map((seg, index) => {
        const utterance = new SpeechSynthesisUtterance(seg.text);

        if (seg.lang === 'en') {
          utterance.lang = 'en-US';
          utterance.rate = 0.95;
          utterance.pitch = 1.0;
          if (englishVoice) {
            utterance.voice = englishVoice;
          }
        } else {
          utterance.lang = 'es-ES';
          utterance.rate = 0.94;
          utterance.pitch = 1.02;
          if (spanishVoice) {
            utterance.voice = spanishVoice;
          }
        }

        // First utterance initiates speaking state
        if (index === 0) {
          utterance.onstart = () => {
            setIsSpeaking(true);
            setSpeakingMessageId(messageId);
          };
        }

        // Last utterance terminates speaking state
        if (index === segments.length - 1) {
          utterance.onend = () => {
            setIsSpeaking(false);
            setSpeakingMessageId(null);
          };
        }

        utterance.onerror = () => {
          setIsSpeaking(false);
          setSpeakingMessageId(null);
        };

        return utterance;
      });

      for (const u of utterances) {
        window.speechSynthesis.speak(u);
      }
    },
    [isSupported, stop],
  );

  const toggle = useCallback(
    (messageId: string, markdownText: string) => {
      if (isSpeaking && speakingMessageId === messageId) {
        stop();
      } else {
        speak(messageId, markdownText);
      }
    },
    [isSpeaking, speakingMessageId, speak, stop],
  );

  useEffect(() => {
    return () => {
      if (typeof window !== 'undefined' && 'speechSynthesis' in window) {
        try {
          window.speechSynthesis.cancel();
        } catch {
          // Ignored on unmount
        }
      }
    };
  }, []);

  return {
    isSupported,
    isSpeaking,
    speakingMessageId,
    speak,
    stop,
    toggle,
  };
}
